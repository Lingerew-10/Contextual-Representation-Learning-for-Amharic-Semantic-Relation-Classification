def calculate_class_f1(confusion_matrix):
    """Calculate per-class F1-scores from a confusion matrix."""

    true_positive = np.diag(confusion_matrix)
    actual_count = confusion_matrix.sum(axis=1)
    predicted_count = confusion_matrix.sum(axis=0)

    precision = np.divide(
        true_positive,
        predicted_count,
        out=np.zeros(NUM_CLASSES, dtype=float),
        where=predicted_count != 0
    )

    recall = np.divide(
        true_positive,
        actual_count,
        out=np.zeros(NUM_CLASSES, dtype=float),
        where=actual_count != 0
    )

    f1 = np.divide(
        2 * precision * recall,
        precision + recall,
        out=np.zeros(NUM_CLASSES, dtype=float),
        where=(precision + recall) != 0
    )

    return f1

