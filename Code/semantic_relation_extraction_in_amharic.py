from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

# Character-level TF-IDF
vectorizer = TfidfVectorizer(
    analyzer="char",
    ngram_range=(3, 5),
    min_df=1,
    sublinear_tf=True
)

sentence_vectors = vectorizer.fit_transform(
    df["sentence"].astype(str)
)

# Calculate sparse cosine similarity
similarity_matrix = cosine_similarity(
    sentence_vectors,
    dense_output=False
)

SIMILARITY_THRESHOLD = 0.90

# Union-Find initialization
parent = list(range(len(df)))

def find_root(x):
    if parent[x] != x:
        parent[x] = find_root(parent[x])
    return parent[x]

def union_groups(a, b):
    root_a = find_root(a)
    root_b = find_root(b)

    if root_a != root_b:
        parent[root_b] = root_a

# Join highly similar sentence pairs
similarity_coo = similarity_matrix.tocoo()

similar_pairs = 0

for i, j, similarity in zip(
    similarity_coo.row,
    similarity_coo.col,
    similarity_coo.data
):
    if i < j and similarity >= SIMILARITY_THRESHOLD:
        union_groups(i, j)
        similar_pairs += 1

# Assign group IDs
df["group_id"] = [
    find_root(i) for i in range(len(df))
]

print("=" * 75)
print("NEAR-DUPLICATE GROUPING RESULTS")
