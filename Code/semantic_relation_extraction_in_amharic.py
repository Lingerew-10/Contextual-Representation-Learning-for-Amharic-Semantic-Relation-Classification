from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score
)
from tqdm.auto import tqdm

def xlm_train_one_epoch(model, loader, optimizer, scheduler):

    model.train()

    total_loss = 0
    all_labels = []
    all_predictions = []

    for batch in tqdm(loader, desc="XLM-R Training", leave=False):

        input_ids = batch["input_ids"].to(DEVICE)
        attention_mask = batch["attention_mask"].to(DEVICE)
        labels = batch["labels"].to(DEVICE)

        optimizer.zero_grad()

        outputs = model(
            input_ids=input_ids,
            attention_mask=attention_mask
        )

        loss = xlm_criterion(outputs.logits, labels)

        loss.backward()

        torch.nn.utils.clip_grad_norm_(
            model.parameters(),
            max_norm=1.0
        )

        optimizer.step()
        scheduler.step()

        total_loss += loss.item()

        predictions = torch.argmax(outputs.logits, dim=1)

        all_labels.extend(labels.cpu().numpy())
        all_predictions.extend(predictions.cpu().numpy())

    metrics = {
        "accuracy": accuracy_score(all_labels, all_predictions),
        "macro_precision": precision_score(
            all_labels, all_predictions,
            average="macro", zero_division=0
        ),
        "macro_recall": recall_score(
            all_labels, all_predictions,
            average="macro", zero_division=0
        ),
        "macro_f1": f1_score(
            all_labels, all_predictions,
            average="macro", zero_division=0
        ),
        "weighted_f1": f1_score(
            all_labels, all_predictions,
            average="weighted", zero_division=0
        )
    }

    return total_loss / len(loader), metrics


def xlm_evaluate(model, loader):

    model.eval()

    total_loss = 0
    all_labels = []
    all_predictions = []

    with torch.no_grad():

        for batch in tqdm(loader, desc="XLM-R Evaluation", leave=False):

            input_ids = batch["input_ids"].to(DEVICE)
            attention_mask = batch["attention_mask"].to(DEVICE)
            labels = batch["labels"].to(DEVICE)

            outputs = model(
                input_ids=input_ids,
                attention_mask=attention_mask
            )

            loss = xlm_criterion(outputs.logits, labels)
            total_loss += loss.item()

            predictions = torch.argmax(outputs.logits, dim=1)

            all_labels.extend(labels.cpu().numpy())
            all_predictions.extend(predictions.cpu().numpy())

    metrics = {
        "accuracy": accuracy_score(all_labels, all_predictions),
        "macro_precision": precision_score(
            all_labels, all_predictions,
            average="macro", zero_division=0
        ),
        "macro_recall": recall_score(
            all_labels, all_predictions,
            average="macro", zero_division=0
        ),
        "macro_f1": f1_score(
            all_labels, all_predictions,
            average="macro", zero_division=0
        ),
        "weighted_f1": f1_score(
            all_labels, all_predictions,
            average="weighted", zero_division=0
        )
    }

    return total_loss / len(loader), metrics


