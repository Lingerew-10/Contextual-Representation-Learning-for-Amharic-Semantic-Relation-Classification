# CELL 68: THREE-ANNOTATOR AGREEMENT AND MAJORITY VOTING

import pandas as pd
import numpy as np

annotator_columns = [
    "Annotator1",
    "Annotator2",
    "Annotator3"
]

# Verify the aligned annotation dataset
if "combined_annotations" not in globals():
    raise ValueError("Please run Cell 67 first.")

# 1. Count agreement for every record
agreement_counts = combined_annotations[
    annotator_columns
].apply(lambda row: row.value_counts(), axis=1)

# Number of matching annotations for each record
combined_annotations["Agreement_Count"] = (
    combined_annotations[annotator_columns]
    .apply(lambda row: row.value_counts().max(), axis=1)
)

# 2. Identify agreement type
def classify_agreement(row):

    unique_labels = row[annotator_columns].nunique()

    if unique_labels == 1:
        return "Unanimous Agreement"

    elif unique_labels == 2:
        return "Majority Agreement"

    else:
        return "Complete Disagreement"

combined_annotations["Agreement_Type"] = (
    combined_annotations.apply(classify_agreement, axis=1)
)

# 3. Determine majority-voting label
def majority_vote(row):

    counts = row[annotator_columns].value_counts()

    # With three annotators, a majority must have at least two votes
    majority_labels = counts[counts >= 2]

    if len(majority_labels) == 1:
        return majority_labels.index[0]

    return "No Majority"

combined_annotations["Majority_Label"] = (
    combined_annotations.apply(majority_vote, axis=1)
)

# 4. Calculate agreement summary
agreement_summary = (
    combined_annotations["Agreement_Type"]
    .value_counts()
    .reindex(
        [
            "Unanimous Agreement",
            "Majority Agreement",
            "Complete Disagreement"
        ],
        fill_value=0
    )
    .rename_axis("Agreement_Type")
    .reset_index(name="Number_of_Records")
)

agreement_summary["Percentage"] = (
    agreement_summary["Number_of_Records"]
    / len(combined_annotations) * 100
).round(2)

print("=" * 85)
print("THREE-ANNOTATOR AGREEMENT SUMMARY")
print("=" * 85)

display(agreement_summary)

# 5. Calculate Fleiss' Kappa manually
categories = sorted(
    set(
        combined_annotations[annotator_columns]
        .values.flatten()
    )
)

N = len(combined_annotations)
n = len(annotator_columns)
k = len(categories)

# Number of annotators assigning each category to each record
category_counts = np.zeros((N, k), dtype=int)

for j, category in enumerate(categories):

    category_counts[:, j] = (
        combined_annotations[annotator_columns]
        .eq(category)
        .sum(axis=1)
        .values
    )

# Agreement for each record
P_i = (
    (category_counts * (category_counts - 1)).sum(axis=1)
    / (n * (n - 1))
)

P_bar = P_i.mean()

# Overall proportion of assignments per category
p_j = category_counts.sum(axis=0) / (N * n)

# Expected agreement by chance
P_e = np.sum(p_j ** 2)

# Fleiss' Kappa
if np.isclose(1 - P_e, 0):
    fleiss_kappa = np.nan
else:
    fleiss_kappa = (P_bar - P_e) / (1 - P_e)

print("\n" + "=" * 85)
print("FLEISS' KAPPA")
print("=" * 85)

print("Number of records:", N)
print("Number of annotators:", n)
print("Number of relation categories:", k)
print("Observed agreement:", round(P_bar, 4))
print("Expected agreement:", round(P_e, 4))
print("Fleiss' Kappa:", round(fleiss_kappa, 4))

# 6. Majority-voting label distribution
print("\n" + "=" * 85)
print("MAJORITY-VOTING LABEL DISTRIBUTION")
print("=" * 85)

majority_distribution = (
    combined_annotations["Majority_Label"]
    .value_counts()
    .reindex(categories, fill_value=0)
    .rename_axis("Relation")
    .reset_index(name="Count")
)

majority_distribution["Percentage"] = (
    majority_distribution["Count"] / N * 100
).round(2)

display(majority_distribution)

# 7. Save annotated dataset and reports
combined_annotations.to_csv(
    "/content/Three_Annotators_Majority_Voting.csv",
    index=False,
    encoding="utf-8-sig"
)

agreement_summary.to_csv(
    "/content/Three_Annotators_Agreement_Summary.csv",
    index=False,
    encoding="utf-8-sig"
)

majority_distribution.to_csv(
    "/content/Majority_Voting_Relation_Distribution.csv",
    index=False,
    encoding="utf-8-sig"
)

